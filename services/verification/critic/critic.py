"""Critic agent: scores a candidate cut and gates delivery.  [Member 3 - Verification, Safety & Generation]

Three scores in [0, 1], each from checks a reviewer can audit:
  safety     (deterministic) - share of hazard screen-time inside the cut that is covered by a mask.
                               Must be exactly 1.0: one unmasked hazard second blocks delivery.
  coherence  (deterministic) - threads ordered, non-overlapping, never cut mid-sentence, prerequisites
                               present for a learner who has not mastered them, explainers available.
  factuality (LLM judge)     - every quiz answer and every explainer storyboard sentence must be
                               supported by the lesson transcript / on-screen text.
Every failed check becomes a structured issue {code, message, ...} that the loop can act on.
"""
import json
import threading

from loom_shared import llm
from loom_shared.config import CACHE_DIR

VERIFIED_CLIPS = CACHE_DIR / "critic_verified_clips.json"
_lock = threading.Lock()

THRESHOLDS = {"factuality": 0.80, "coherence": 0.80, "safety": 1.0}
PREREQ_MASTERY = 0.35

JUDGE_SYSTEM = """You are a strict fact-checker for an educational video system.
You get the lesson SOURCE (transcript and on-screen text) and numbered CLAIMS generated by other AI agents
(quiz questions with their marked answer, and narration lines of generated explainer animations).
A claim is "supported" if it is correct AND consistent with the source (general textbook facts that agree
with the source are fine). It is "unsupported" if it is wrong, contradicts the source, or overstates it
(e.g. "always", or saying a dissolved product is a solid).
Return JSON: {"verdicts": [{"id": int, "supported": bool, "reason": short string}]}"""


def _sentence_bounds(graph):
    return [(s["start"], s["end"]) for s in graph["transcript"]]


def coherence(candidate, graph, profile, explainer_failures):
    issues = []
    threads = candidate["threads"]
    penalty = 0.0
    if not threads:
        return 0.0, [{"code": "empty_cut", "message": "the cut contains no threads"}]
    starts = [t["start"] for t in threads]
    if starts != sorted(starts) or any(b["start"] < a["end"] - 0.05 for a, b in zip(threads, threads[1:])):
        penalty += 0.25
        issues.append({"code": "overlapping_threads", "message": "threads overlap or are out of order"})
    for t in threads:
        for s, e in _sentence_bounds(graph):
            if s + 0.3 < t["end"] < e - 0.3:
                penalty += 0.15
                issues.append({"code": "cut_mid_sentence", "thread_id": t["thread_id"],
                               "message": f"{t['thread_id']} ends mid-sentence at {t['end']:.1f}s (sentence ends {e:.1f}s)"})
                break
    mastery = {m["concept_id"].split("/")[-1]: m["level"] for m in profile.get("mastery_graph", [])}
    prior = profile.get("preferences", {}).get("prior_knowledge", 0.3)
    in_cut = {c for t in threads for c in t["concept_node_ids"]}
    for node in graph["concept_nodes"]:
        if node["node_id"] not in in_cut:
            continue
        for p in node.get("prerequisites", []):
            if p not in in_cut and mastery.get(p, prior) < PREREQ_MASTERY:
                penalty += 0.1
                issues.append({"code": "missing_prerequisite", "concept_node_id": p,
                               "message": f"{node['node_id']} needs {p}, which this learner has not mastered"})
    for cid, err in explainer_failures.items():
        penalty += 0.1
        issues.append({"code": "explainer_unavailable", "concept_node_id": cid,
                       "message": f"explainer for {cid} could not be produced: {err[:120]}"})
    return round(max(0.0, 1.0 - penalty), 3), issues


def safety(candidate, graph, flagged, masks):
    """Coverage of flagged-object screen time (within the cut) by masks, measured per 0.1 s."""
    threads = candidate["threads"]
    need = covered = 0
    uncovered = set()
    for obj in graph["objects"]:
        if obj["object_id"] not in flagged:
            continue
        obj_masks = [m for m in masks if m["object_id"] == obj["object_id"]]
        for inst in obj["instances"]:
            t = inst["start"]
            while t < inst["end"]:
                if any(th["start"] <= t < th["end"] for th in threads):
                    need += 1
                    if any(m["start"] <= t < m["end"] for m in obj_masks):
                        covered += 1
                    else:
                        uncovered.add(obj["object_id"])
                t = round(t + 0.1, 2)
    score = 1.0 if need == 0 else covered / need
    issues = [{"code": "unmasked_hazard", "object_id": o, "message": f"{o} is visible without a mask"}
              for o in sorted(uncovered)]
    return round(score, 3), issues


def _verified_clips():
    return json.loads(VERIFIED_CLIPS.read_text()) if VERIFIED_CLIPS.exists() else {}


def _remember_verified(clips):
    with _lock:
        known = _verified_clips()
        known.update(clips)
        VERIFIED_CLIPS.write_text(json.dumps(known, indent=2))


def factuality(candidate, graph, explainers):
    claims = []
    for i, q in enumerate(candidate.get("quiz", [])):
        answer = q["options"][q["answer_index"]] if q.get("options") else ""
        claims.append({"kind": "quiz", "index": i, "text": f"Q: {q['question']} -> marked answer: {answer}"})
    # An explainer clip is immutable once rendered: if the Critic already passed it, it stays passed.
    known = _verified_clips()
    pre_verified = 0
    for cid, ex in explainers.items():
        if ex.get("clip_url") in known:
            pre_verified += len(ex.get("storyboard", []))
            continue
        for line in ex.get("storyboard", []):
            claims.append({"kind": "explainer", "concept_node_id": cid, "text": line, "clip_url": ex.get("clip_url")})
    if not claims:
        return 1.0, [], []
    source = "\n".join(s["text"] for s in graph["transcript"]) + "\nON SCREEN: " + \
        " | ".join(o["text"] for o in graph.get("on_screen_text", []))
    listing = "\n".join(f"[{i}] {c['text']}" for i, c in enumerate(claims))
    try:
        verdicts = llm.complete(JUDGE_SYSTEM, f"SOURCE:\n{source}\n\nCLAIMS:\n{listing}", temperature=0)["verdicts"]
    except Exception as e:
        return 0.0, [{"code": "judge_unavailable", "message": f"fact-check failed: {e}"}], []
    by_id = {v.get("id"): v for v in verdicts if isinstance(v, dict)}
    issues, details, supported = [], [], 0
    bad_explainers = {}
    for i, c in enumerate(claims):
        v = by_id.get(i, {"supported": False, "reason": "no verdict returned"})
        ok = bool(v.get("supported"))
        supported += ok
        details.append({**c, "supported": ok, "reason": v.get("reason", "")})
        if not ok and c["kind"] == "quiz":
            issues.append({"code": "quiz_unsupported", "index": c["index"],
                           "message": f"quiz {c['index']}: {v.get('reason', '')}"})
        elif not ok:
            bad_explainers.setdefault(c["concept_node_id"], []).append(f"'{c['text']}': {v.get('reason', '')}")
    for cid, reasons in bad_explainers.items():
        issues.append({"code": "explainer_unfaithful", "concept_node_id": cid, "feedback": reasons,
                       "message": f"explainer {cid}: " + "; ".join(reasons)[:200]})
    passed = {ex["clip_url"]: cid for cid, ex in explainers.items()
              if ex.get("clip_url") and cid not in bad_explainers and ex.get("clip_url") not in known}
    if passed:
        _remember_verified(passed)
    return round((supported + pre_verified) / (len(claims) + pre_verified), 3), issues, details


def score(candidate, graph, profile, flagged, masks, explainers, explainer_failures):
    s_saf, i_saf = safety(candidate, graph, flagged, masks)
    s_coh, i_coh = coherence(candidate, graph, profile, explainer_failures)
    s_fac, i_fac, details = factuality(candidate, graph, explainers)
    scores = {"factuality": s_fac, "coherence": s_coh, "safety": s_saf}
    # Averages hide individual failures: every check must pass on its own. Any issue sends the cut back
    # through the loop (the mesh can fix structural issues cheaply); the scores are reported, not traded off.
    issues = i_saf + i_coh + i_fac
    approved = all(scores[k] >= THRESHOLDS[k] for k in THRESHOLDS) and not issues
    return {"scores": scores, "approved": approved, "issues": issues, "claims": details}


def handle(skill, data):
    return score(data["candidate_cut"], data["concept_graph"], data["learner_profile"], set(data.get("flagged", [])),
                 data.get("redaction_masks", []), data.get("explainers", {}), data.get("explainer_failures", {}))
