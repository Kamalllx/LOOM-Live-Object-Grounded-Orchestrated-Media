"""`loom sync-extension` — give the YouTube extension the web player's explainer scene (3-D scenes and exact
constructions), so both always play the same thing.

The web page loads `static/scene.js` as an ES module with an import map ("three", "three/addons/..."). An extension
has no import map, so the copy (`extension/scene3d.js`) and the vendored three.js addons get relative import paths;
GSAP is copied as a classic script the manifest loads before `content.js`. Run after changing `static/scene.js` or
the vendored libraries, then reload the extension.
"""

from __future__ import annotations

import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATIC = ROOT / "loom" / "gateway" / "static"
EXT = ROOT / "extension"
THREE_FILES = ["three.module.min.js", "LICENSE"]
HEADER = ("// GENERATED by `uv run loom sync-extension` from loom/gateway/static/scene.js - do not edit here.\n"
          "// The extension imports it with import(chrome.runtime.getURL('scene3d.js')).\n")


def _rel(spec: str, from_dir: Path) -> str:
    """'three' / 'three/addons/x.js' -> a path relative to the importing file (extension layout)."""
    target = EXT / "vendor" / "three" / ("three.module.min.js" if spec == "three" else spec.removeprefix("three/"))
    rel = Path(*([".."] * len(from_dir.relative_to(EXT).parts))) / target.relative_to(EXT)
    s = rel.as_posix()
    return s if s.startswith("..") else "./" + s


def _rewrite(code: str, from_dir: Path) -> str:
    return re.sub(r"""from\s+(["'])(three(?:/[^"']*)?)\1""", lambda m: f'from "{_rel(m.group(2), from_dir)}"', code)


def sync() -> list[str]:
    written = []
    vendor = EXT / "vendor"
    if vendor.exists():
        shutil.rmtree(vendor)
    (vendor / "three").mkdir(parents=True)
    for name in THREE_FILES:
        shutil.copyfile(STATIC / "vendor" / "three" / name, vendor / "three" / name)
        written.append(f"vendor/three/{name}")
    for src in sorted((STATIC / "vendor" / "three" / "addons").rglob("*.js")):
        dest = vendor / "three" / src.relative_to(STATIC / "vendor" / "three")
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(_rewrite(src.read_text(encoding="utf-8"), dest.parent), encoding="utf-8")
        written.append(dest.relative_to(EXT).as_posix())
    shutil.copyfile(STATIC / "vendor" / "gsap.min.js", vendor / "gsap.min.js")
    written.append("vendor/gsap.min.js")
    scene = _rewrite((STATIC / "scene.js").read_text(encoding="utf-8"), EXT)
    (EXT / "scene3d.js").write_text(HEADER + scene, encoding="utf-8")
    written.append("scene3d.js")
    return written


if __name__ == "__main__":
    for w in sync():
        print(w)
